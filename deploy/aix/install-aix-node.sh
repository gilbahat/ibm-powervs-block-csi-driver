# Installs the IBM PowerVS block CSI node plugin on an AIX node as an SRC
# subsystem. The controller keeps running on Linux.
#
# The node plugin cannot run as a DaemonSet pod on AIX: it creates volume
# groups and mounts file systems into the kubelet's directories, which from a
# container needs device access and Bidirectional mount propagation. AIX has
# no mount propagation and containerd-aix gives WPARs neither. It runs on the
# host instead, as the kubelet does, and registers itself with the kubelet
# (no node-driver-registrar sidecar).
#
# Settings, from the environment:
#   BIN          plugin binary   (/opt/ibm-powervs-block-csi-driver/bin/ibm-powervs-block-csi-driver)
#   NODE_NAME    Kubernetes node name (lower-cased hostname, as the kubelet uses)
#   KUBECONFIG   kubeconfig the plugin reads its Node's providerID with; the
#                kubelet's own kubeconfig is enough (the node authorizer lets it
#                read its Node). Not needed when POWERVS_CLOUD_INSTANCE_ID,
#                POWERVS_ZONE and POWERVS_INSTANCE_ID are all set.
#   API_KEY_FILE IBM Cloud API key file, readable only by root
#                (/etc/ibm-powervs-csi/IBMCLOUD_API_KEY)
#   POWERVS_CLOUD_INSTANCE_ID, POWERVS_ZONE, POWERVS_INSTANCE_ID
#                optional: the workspace, zone and VM, instead of the providerID
#   IBMCLOUD_IAM_API_ENDPOINT, IBMCLOUD_RESOURCE_CONTROLLER_ENDPOINT
#                optional: private or non-default IBM Cloud endpoints
#   KUBELET_DIR  kubelet root directory (/var/lib/kubelet)
#   SUBSYS       SRC subsystem name (csi-powervs)
#   GROUP        SRC group (kubernetes)
#   LOG          log file (/var/log/csi-powervs.log)
#   EXTRA_ARGS   more plugin flags, e.g. "--volume-attach-limit=60"
#   NO_INITTAB   set to 1 to skip the /etc/inittab entry that starts it at boot

set -e

BIN=${BIN:-/opt/ibm-powervs-block-csi-driver/bin/ibm-powervs-block-csi-driver}
NODE_NAME=${NODE_NAME:-$(hostname | tr '[:upper:]' '[:lower:]')}
API_KEY_FILE=${API_KEY_FILE:-/etc/ibm-powervs-csi/IBMCLOUD_API_KEY}
KUBELET_DIR=${KUBELET_DIR:-/var/lib/kubelet}
SUBSYS=${SUBSYS:-csi-powervs}
GROUP=${GROUP:-kubernetes}
LOG=${LOG:-/var/log/csi-powervs.log}
EXTRA_ARGS=${EXTRA_ARGS:-}

CONF_DIR=/etc/ibm-powervs-csi
ENV_FILE=${CONF_DIR}/node.env
WRAPPER=$(dirname "${BIN}")/powervs-csi-node
SOCK_DIR=${KUBELET_DIR}/plugins/powervs.csi.ibm.com
REG_DIR=${KUBELET_DIR}/plugins_registry
SOCK=${SOCK_DIR}/csi.sock

fail() {
	echo "$*" >&2
	exit 1
}

[ "$(uname -s)" = "AIX" ] || fail "this script is for AIX"
[ -x "${BIN}" ] || fail "${BIN} not found or not executable"
[ -r "${API_KEY_FILE}" ] || fail "API key file ${API_KEY_FILE} not found"
if [ -n "$(find "${API_KEY_FILE}" -perm -004 2>/dev/null)" ]; then
	fail "${API_KEY_FILE} is world-readable; chmod 600 it"
fi
if [ -z "${POWERVS_CLOUD_INSTANCE_ID}" ] || [ -z "${POWERVS_ZONE}" ] || [ -z "${POWERVS_INSTANCE_ID}" ]; then
	[ -n "${KUBECONFIG}" ] && [ -r "${KUBECONFIG}" ] ||
		fail "set KUBECONFIG (e.g. the kubelet's kubeconfig), or all of POWERVS_CLOUD_INSTANCE_ID, POWERVS_ZONE and POWERVS_INSTANCE_ID"
fi
for cmd in mkvg importvg exportvg crfs chfs cfgmgr lspath; do
	whence "${cmd}" >/dev/null 2>&1 || fail "${cmd} not found"
done

mkdir -p "${CONF_DIR}" "${SOCK_DIR}" "${REG_DIR}"
chmod 0700 "${CONF_DIR}"
chmod 0750 "${SOCK_DIR}"

# The plugin reads its settings from the environment, which SRC does not
# pass, so the subsystem runs a wrapper that loads them from ENV_FILE.
umask 077
{
	echo "CSI_NODE_NAME=${NODE_NAME}"
	echo "API_KEY_PATH=${API_KEY_FILE}"
	for v in POWERVS_CLOUD_INSTANCE_ID POWERVS_ZONE POWERVS_INSTANCE_ID \
		IBMCLOUD_IAM_API_ENDPOINT IBMCLOUD_RESOURCE_CONTROLLER_ENDPOINT; do
		eval "val=\${${v}}"
		[ -n "${val}" ] && echo "${v}=${val}"
	done
} > "${ENV_FILE}"
umask 022

cat > "${WRAPPER}" <<WRAP
#!/usr/bin/ksh
# Generated by install-aix-node.sh: loads ${ENV_FILE} and runs the plugin.
set -a
. ${ENV_FILE}
set +a
exec ${BIN} "\$@"
WRAP
chmod 0755 "${WRAPPER}"

ARGS="node --logtostderr --v=2 --endpoint=unix://${SOCK}"
ARGS="${ARGS} --kubelet-registration-path=${SOCK} --plugin-registration-dir=${REG_DIR}"
[ -n "${KUBECONFIG}" ] && ARGS="${ARGS} --kubeconfig=${KUBECONFIG}"
ARGS="${ARGS} ${EXTRA_ARGS}"

if lssrc -s "${SUBSYS}" >/dev/null 2>&1; then
	stopsrc -s "${SUBSYS}" >/dev/null 2>&1 || true
	rmssys -s "${SUBSYS}"
fi

# -R: restart on abnormal exit (a failed kubelet registration exits 1)
# -Q: one instance; -S -n 15 -f 9: stop with SIGTERM, force with SIGKILL
mkssys -s "${SUBSYS}" -p "${WRAPPER}" -a "${ARGS}" -u 0 -G "${GROUP}" \
	-R -Q -S -n 15 -f 9 -w 30 -o "${LOG}" -e "${LOG}"

# inittab identifiers are at most 14 characters.
ITAB_ID=$(echo "${SUBSYS}" | tr -cd '[:alnum:]' | cut -c1-14)
if [ "${NO_INITTAB}" != "1" ]; then
	rmitab "${ITAB_ID}" >/dev/null 2>&1 || true
	mkitab "${ITAB_ID}:2:once:/usr/bin/startsrc -s ${SUBSYS} >/dev/console 2>&1"
fi

startsrc -s "${SUBSYS}"
echo "${SUBSYS} installed for node ${NODE_NAME}; logs in ${LOG}"
